import 'cypress-real-events';
import * as React from 'react';
import { mount as mountBase } from '@fluentui/scripts-cypress';
import { FluentProvider } from '@fluentui/react-provider';
import { teamsLightTheme } from '@fluentui/react-theme';
import type { JSXElement } from '@fluentui/react-utilities';
import { Portal } from '@fluentui/react-portal';

const mount = (element: JSXElement) => {
  mountBase(<FluentProvider theme={teamsLightTheme}>{element}</FluentProvider>);
};

const PORTAL_NODE_SELECTOR = '[data-portal-node="true"]';

describe('Portal (usePortalMountNode)', () => {
  it('mounts children into a portal node attached to document.body', () => {
    mount(
      <div data-testid="origin">
        <Portal>
          <div data-testid="portal-content">portal content</div>
        </Portal>
      </div>,
    );

    cy.get('[data-testid="portal-content"]').should('exist').and('have.text', 'portal content');
    cy.get(PORTAL_NODE_SELECTOR).should('exist');
    cy.get(PORTAL_NODE_SELECTOR).then($node => {
      expect($node.get(0).parentElement, 'portal node parent').to.equal(document.body);
    });
    // origin div should NOT contain the portal content (it's portaled to body)
    cy.get('[data-testid="origin"]').find('[data-testid="portal-content"]').should('not.exist');
  });

  it('keeps focus inside the portal content after parent re-renders', () => {
    const Wrapper: React.FC = () => {
      const [, force] = React.useReducer(x => x + 1, 0);
      return (
        <>
          <button id="rerender" onClick={() => force()}>
            rerender
          </button>
          <Portal>
            <input data-testid="portal-input" />
          </Portal>
        </>
      );
    };

    mount(<Wrapper />);

    cy.get('[data-testid="portal-input"]').realClick();
    cy.focused().should('have.attr', 'data-testid', 'portal-input');

    cy.get('#rerender').realClick();
    // After parent re-renders, the portal node identity must remain stable so the
    // mounted input is not re-created and focus is preserved.
    cy.get(PORTAL_NODE_SELECTOR).should('have.length', 1);
    cy.get('[data-testid="portal-input"]').should('exist');
  });

  it('keeps a single mount node when re-rendering the same Portal', () => {
    const Wrapper: React.FC = () => {
      const [, force] = React.useReducer(x => x + 1, 0);
      return (
        <>
          <button id="rerender" onClick={() => force()}>
            rerender
          </button>
          <Portal>
            <div data-testid="portal-content">portal content</div>
          </Portal>
        </>
      );
    };

    mount(<Wrapper />);

    cy.get(PORTAL_NODE_SELECTOR).should('have.length', 1);
    cy.get('#rerender').realClick().realClick().realClick();
    cy.get(PORTAL_NODE_SELECTOR).should('have.length', 1);
    cy.get('[data-testid="portal-content"]').should('exist');
  });

  it('renders into a custom mountNode when provided', () => {
    const CustomMount: React.FC = () => {
      const [mountNode, setMountNode] = React.useState<HTMLElement | null>(null);
      return (
        <>
          <div id="custom-mount" ref={setMountNode} data-testid="custom-mount" />
          {mountNode && (
            <Portal mountNode={mountNode}>
              <div data-testid="portal-content">portal content</div>
            </Portal>
          )}
        </>
      );
    };

    mount(<CustomMount />);

    cy.get('[data-testid="custom-mount"]').find('[data-testid="portal-content"]').should('exist');
    // No autogenerated mount node should exist on document.body when a custom mountNode is supplied
    cy.get(PORTAL_NODE_SELECTOR).should('have.length', 0);
  });

  it('supports nested portals', () => {
    mount(
      <Portal>
        <div data-testid="outer-portal">
          outer
          <Portal>
            <div data-testid="inner-portal">inner</div>
          </Portal>
        </div>
      </Portal>,
    );

    cy.get('[data-testid="outer-portal"]').should('exist');
    cy.get('[data-testid="inner-portal"]').should('exist');
    cy.get(PORTAL_NODE_SELECTOR).should('have.length.at.least', 2);
  });
});
